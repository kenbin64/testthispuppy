package com.testthispuppy;

import java.io.IOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Turns a site map into a test plan, written to a folder outside the site:
 *   PLAN.md          what was found, what each form likely writes, and what a person must confirm
 *   plan.properties  the settings to run it, aimed at a COPY of the site (the live address is recorded as a guard)
 *   pages.txt        each page with a form that writes: happy path and wrong input in every field
 *   http-cases.txt   every page answers; every search answers
 *   macros/          one workflow per writing form: fill it with fresh dummy data, submit, check nothing broke, and
 *                    (once confirmed) check the database row it should have created
 * Searches (GET forms) also become cross-site scripting targets. Sign-in forms get no generated submit: a real test
 * account is needed, and guessing passwords is never done.
 */
public final class PlanWriter {
    private PlanWriter() {
    }

    public static void write(Path folder, String liveUrl, String copyUrl, List<SiteMapper.Page> pages) throws IOException {
        Files.createDirectories(folder.resolve("macros"));
        List<SiteMapper.Form> forms = pages.stream().flatMap(p -> p.forms().stream()).toList();
        List<SiteMapper.Form> writing = forms.stream().filter(f -> f.writes() && !f.signIn()).toList();
        List<SiteMapper.Form> searches = forms.stream().filter(f -> !f.writes() && !f.signIn() && firstTextField(f) != null).toList();
        List<SiteMapper.Form> signIns = forms.stream().filter(SiteMapper.Form::signIn).toList();

        List<String> macroNames = new ArrayList<>();
        for (SiteMapper.Form form : writing) {
            String name = slug(path(form.page())) + "-to-" + slug(path(form.action()));
            Files.writeString(folder.resolve("macros").resolve(name + ".txt"), macro(form), StandardCharsets.UTF_8);
            macroNames.add(name);
        }
        Files.writeString(folder.resolve("pages.txt"), pagesTable(writing), StandardCharsets.UTF_8);
        Files.writeString(folder.resolve("http-cases.txt"), httpCases(pages, searches), StandardCharsets.UTF_8);
        Files.writeString(folder.resolve("plan.properties"), settings(liveUrl, copyUrl, searches), StandardCharsets.UTF_8);
        Files.writeString(folder.resolve("PLAN.md"), planText(liveUrl, copyUrl, pages, writing, searches, signIns, macroNames), StandardCharsets.UTF_8);
    }

    /** A workflow for one writing form: fill every field, submit, check no server error, and the database check to confirm. */
    static String macro(SiteMapper.Form form) {
        StringBuilder m = new StringBuilder();
        m.append("# Generated by TestThisPuppy's site mapper from ").append(form.page()).append("\n")
                .append("# The form sends to ").append(path(form.action())).append(" (").append(form.method().toUpperCase()).append(")")
                .append(form.submit().isBlank() ? "" : ", button \"" + form.submit() + "\"").append(". Review before relying on it.\n")
                .append("action         | target                | value\n")
                .append(String.format("%-14s | %-21s |%n", "open", path(form.page())));
        for (SiteMapper.Field f : form.fields()) {
            String step = step(f);
            if (step != null) {
                m.append(step).append('\n');
            }
        }
        m.append(String.format("%-14s | %-21s |%n", "submit", ""))
                .append(String.format("%-14s | %-21s | %s%n", "expect-no-text", "", "Exception"))
                .append("# TODO: the words the page shows after a successful save, then remove the # below:\n")
                .append("# expect-text   |                       | Saved\n");
        SiteMapper.Field key = keyField(form);
        if (key != null) {
            m.append("# Database check: did the save really store what was typed? The table and column are GUESSES from the form;\n")
                    .append("# confirm them against the copy's database, then remove the # below:\n")
                    .append(String.format("# expect-row    | %-21s | %s={typed:%s}%n", tableGuess(form.action()), columnGuess(key.name()), key.name()));
        }
        return m.toString();
    }

    /** A password for test accounts created on the copy (sign-up forms). Never used to try signing in to anything. */
    static final String TEST_PASSWORD = "Puppy-Test-Pass-7319!";

    /** The macro step that fills one field, or null for a field a macro should leave alone (an optional checkbox). */
    static String step(SiteMapper.Field f) {
        String target = "name=" + f.name();
        return switch (f.type()) {
            case "password" -> String.format("%-14s | %-21s | %s", "type", target, TEST_PASSWORD);
            case "checkbox", "radio" -> f.required() ? String.format("%-14s | %-21s |", "check", target) : null;
            case "select-one", "select-multiple" -> String.format("%-14s | %-21s | first", "select", target);
            default -> String.format("%-14s | %-21s | %s", "type", target, dummyFor(f));
        };
    }

    static String dummyFor(SiteMapper.Field f) {
        String name = f.name().toLowerCase(Locale.ROOT);
        return switch (f.type()) {
            case "email" -> "{dummy:email}";
            case "tel" -> "{dummy:phone}";
            case "number", "range" -> f.min().isBlank() ? "{dummy:number}" : f.min();
            case "date" -> "{dummy:date}";
            case "url" -> "https://example.test";
            default -> name.contains("email") ? "{dummy:email}" : name.contains("phone") || name.contains("tel") ? "{dummy:phone}"
                    : name.contains("name") ? "{dummy:name}" : "{dummy:text}";
        };
    }

    /** The field most likely to find the saved row: an email, else the first required text field, else the first text field. */
    static SiteMapper.Field keyField(SiteMapper.Form form) {
        List<SiteMapper.Field> texts = form.fields().stream().filter(f -> List.of("text", "email", "tel", "textarea", "").contains(f.type())).toList();
        return texts.stream().filter(f -> f.type().equals("email") || f.name().toLowerCase(Locale.ROOT).contains("email")).findFirst()
                .orElse(texts.stream().filter(SiteMapper.Field::required).findFirst().orElse(texts.isEmpty() ? null : texts.get(0)));
    }

    /** A table name guessed from where the form sends: the last word of the address, made singular. A guess to confirm. */
    static String tableGuess(String action) {
        String[] parts = path(action).replaceAll("\\?.*", "").split("/");
        for (int i = parts.length - 1; i >= 0; i--) {
            String p = parts[i].toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9_]", "_");
            if (!p.isBlank() && !p.matches("\\d+|new|create|save|submit|add|edit|update|api|v\\d+")) {
                return p.endsWith("ies") ? p.substring(0, p.length() - 3) + "y" : p.endsWith("s") && p.length() > 3 ? p.substring(0, p.length() - 1) : p;
            }
        }
        return "TODO_table";
    }

    /** A column name guessed from a field name: firstName becomes first_name. */
    static String columnGuess(String field) {
        return field.replaceAll("([a-z0-9])([A-Z])", "$1_$2").replaceAll("[^A-Za-z0-9_]", "_").toLowerCase(Locale.ROOT);
    }

    static String firstTextField(SiteMapper.Form form) {
        return form.fields().stream().filter(f -> List.of("text", "search", "").contains(f.type())).map(SiteMapper.Field::name).findFirst().orElse(null);
    }

    private static String pagesTable(List<SiteMapper.Form> writing) {
        StringBuilder t = new StringBuilder("# Pages with a form that writes: happy path (every field filled) and wrong input in each field.\n"
                + "# TODO: replace each expectedText with the words the page shows after a successful save.\n"
                + "name | path | expectedText\n");
        Set<String> done = new LinkedHashSet<>();
        for (SiteMapper.Form f : writing) {
            if (done.add(path(f.page()))) {
                t.append("form on ").append(path(f.page())).append(" | ").append(path(f.page())).append(" | TODO success text\n");
            }
        }
        return t.toString();
    }

    private static String httpCases(List<SiteMapper.Page> pages, List<SiteMapper.Form> searches) {
        StringBuilder t = new StringBuilder("# Every mapped page answers, and every search answers.\nname | method | path | body | expectedStatus | expectedText\n");
        for (SiteMapper.Page p : pages) {
            t.append("GET ").append(path(p.url())).append(" answers | GET | ").append(path(p.url())).append(" |  | 200 |\n");
        }
        for (SiteMapper.Form s : searches) {
            String q = path(s.action()) + (path(s.action()).contains("?") ? "&" : "?") + firstTextField(s) + "=Lorem";
            t.append("search ").append(q).append(" answers | GET | ").append(q).append(" |  | 200 |\n");
        }
        return t.toString();
    }

    private static String settings(String liveUrl, String copyUrl, List<SiteMapper.Form> searches) {
        List<String> xss = searches.stream().map(s -> path(s.action()).replaceAll("\\?.*", "") + "?" + firstTextField(s) + "=").distinct().toList();
        return "# Test plan for " + liveUrl + ", generated " + LocalDate.now() + " by TestThisPuppy's site mapper.\n"
                + "#   mvn -q -f <testthispuppy>/puppy/pom.xml exec:java -Dexec.args=plan.properties\n"
                + "# Plans submit forms, so they run against a COPY of the site, never the live one. The guard refuses a run\n"
                + "# whose app.baseUrl is the live site.\n"
                + "guard.liveUrl=" + liveUrl + "\n"
                + "app.baseUrl=" + copyUrl + "\n\n"
                + "# The copy's database, so the run can seed it, check what forms stored (expect-row), and put it back exactly.\n"
                + "db.mode=external\ndb.url=TODO jdbc:postgresql://localhost:5432/copy_db\ndb.user=TODO\ndb.password=TODO\n"
                + "db.allowed=TODO jdbc:postgresql://localhost:5432/copy_db\n\n"
                + "browser.pages=pages.txt\nbrowser.checks=happy,wrong-input\nbrowser.macros=macros\nhttp.cases=http-cases.txt\n"
                + "report.file=report-plan.json\n"
                + (xss.isEmpty() ? "" : "\n# Searches found on the site: tested for reflected cross-site scripting.\nxss.paths=" + String.join(",", xss) + "\n");
    }

    private static String planText(String liveUrl, String copyUrl, List<SiteMapper.Page> pages, List<SiteMapper.Form> writing,
                                   List<SiteMapper.Form> searches, List<SiteMapper.Form> signIns, List<String> macroNames) {
        StringBuilder md = new StringBuilder("# Test plan for " + liveUrl + "\n\n");
        md.append("Generated ").append(LocalDate.now()).append(" by TestThisPuppy's site mapper, which only read the site: it opened ")
                .append(pages.size()).append(" page(s) and submitted nothing.\n\n")
                .append("| Found | Count | What the plan does with them |\n|---|---|---|\n")
                .append("| Forms that write (POST) | ").append(writing.size()).append(" | a workflow each (fill, submit, check), plus happy path and wrong input in every field |\n")
                .append("| Searches (GET forms) | ").append(searches.size()).append(" | each must answer; each is tested for reflected cross-site scripting |\n")
                .append("| Sign-in forms | ").append(signIns.size()).append(" | not submitted: they need a real test account, and passwords are never guessed |\n\n");
        md.append("## Forms that write, and what they likely store\n\n");
        if (writing.isEmpty()) {
            md.append("None found.\n");
        }
        for (int i = 0; i < writing.size(); i++) {
            SiteMapper.Form f = writing.get(i);
            SiteMapper.Field key = keyField(f);
            md.append("- **").append(path(f.page())).append("** sends to `").append(path(f.action())).append("`")
                    .append(f.submit().isBlank() ? "" : " (\"" + f.submit() + "\")").append(": ")
                    .append(String.join(", ", f.fields().stream().map(x -> x.name() + (x.required() ? "*" : "") + " (" + (x.type().isBlank() ? x.tag() : x.type()) + ")").toList()))
                    .append(". Likely a row in `").append(tableGuess(f.action())).append("`")
                    .append(key == null ? "" : ", found again by `" + columnGuess(key.name()) + "`").append(". Workflow: `macros/").append(macroNames.get(i)).append(".txt`.\n");
        }
        md.append("\n(* = required)\n\n## Before running\n\n")
                .append("1. Start a copy of the site: a staging server, or the app built from its source on your machine. ")
                .append("Its database must be a copy too. Point `app.baseUrl` in `plan.properties` at it (now `").append(copyUrl).append("`).\n")
                .append("2. Fill in the copy's database in `plan.properties` (the `db.` lines). TestThisPuppy seeds it, runs the plan, and puts it back exactly as it was.\n")
                .append("3. In `pages.txt` and each workflow, replace the TODO with the words the page shows after a successful save.\n")
                .append("4. For each workflow's database check, confirm the table and column (they are guesses from the form) and remove the `#`.\n")
                .append("5. Run it: `mvn -q -f <testthispuppy>/puppy/pom.xml exec:java -Dexec.args=plan.properties`. ")
                .append("It refuses to run if `app.baseUrl` is the live site.\n\n")
                .append("What a person decides here, the tool cannot: what a successful save says, which table a form writes to, and a test account for sign-in. ")
                .append("Everything else was generated.\n");
        return md.toString();
    }

    static String path(String url) {
        URI u = URI.create(url);
        String p = u.getRawPath() == null || u.getRawPath().isEmpty() ? "/" : u.getRawPath();
        return u.getRawQuery() == null ? p : p + "?" + u.getRawQuery();
    }

    static String slug(String path) {
        String s = path.replaceAll("\\?.*", "").replaceAll("[^A-Za-z0-9]+", "-").replaceAll("^-|-$", "").toLowerCase(Locale.ROOT);
        return s.isEmpty() ? "home" : s;
    }
}
